"""Turns a rendered mascot PNG into the small Luxi sprite used by the LuxiFlap easter egg.

Usage: make_flap_sprite.py <mascot.png> <size> <out.h> [preview.png]
Unlike make_sprite.py, transparency is kept: each row also gets a bit mask (bit x set = opaque),
so Luxi can be drawn over the game's sky. Render the PNG from branding/luxi-mascot.svg with a
transparent background (e.g. a headless browser with --default-background-color=00000000).
"""
import sys
from PIL import Image

src, size, dst = sys.argv[1], int(sys.argv[2]), sys.argv[3]
assert size <= 32, 'the row mask is a u32'
img = Image.open(src).convert('RGBA')
img = img.crop(img.getbbox()).resize((size, size), Image.LANCZOS)

vals, masks = [], []
for y in range(size):
    m = 0
    for x in range(size):
        r, g, b, a = img.getpixel((x, y))
        if a >= 128:
            m |= 1 << x
        vals.append((r >> 3) << 11 | (g >> 2) << 5 | (b >> 3))
    masks.append(m)

if len(sys.argv) > 4:
    prev = Image.new('RGBA', (size, size), (27, 32, 69, 255))  # the game's sky colour
    for y in range(size):
        for x in range(size):
            if masks[y] >> x & 1:
                prev.putpixel((x, y), img.getpixel((x, y))[:3] + (255,))
    prev.resize((size * 8, size * 8), Image.NEAREST).save(sys.argv[4])

lines = []
for i in range(0, len(vals), 12):
    lines.append('    ' + ', '.join(f'0x{v:04X}' for v in vals[i:i + 12]) + ',')
mask_lines = []
for i in range(0, len(masks), 6):
    mask_lines.append('    ' + ', '.join(f'0x{m:08X}' for m in masks[i:i + 6]) + ',')

with open(dst, 'w', encoding='utf-8', newline='\n') as f:
    f.write(f'''// Generated by luxios-tools/make_flap_sprite.py from branding/luxi-mascot.svg -- do not edit by hand.
// Luxi for the LuxiFlap easter egg: {size}x{size} RGB565, row-major, plus one opacity bit mask per row.
#pragma once

#include <3ds/types.h>

#define LUXI_FLAP_SPRITE_SIZE {size}

static const u16 luxiFlapSprite[LUXI_FLAP_SPRITE_SIZE * LUXI_FLAP_SPRITE_SIZE] = {{
''' + '\n'.join(lines) + '''
};

static const u32 luxiFlapMask[LUXI_FLAP_SPRITE_SIZE] = {
''' + '\n'.join(mask_lines) + '\n};\n')
print('ok', dst, len(vals))
