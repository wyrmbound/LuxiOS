// Host-side test for LuxiOS's bounded vsnprintf (arm9/rosalina fmt.c).
// fmt.c is compiled with its functions renamed to l* so they don't clash with libc.
#include <stdio.h>
#include <string.h>
#include <stdarg.h>

int lsnprintf(char *buf, size_t size, const char *fmt, ...);
int lsprintf(char *buf, const char *fmt, ...);

static int failures = 0, checks = 0;

#define CANARY 0x5A

// Compare one format against libc for every buffer size from 0 to len+2
#define CHECK(...) do { \
    char expect[256]; \
    int expLen = snprintf(expect, sizeof(expect), __VA_ARGS__); \
    for (size_t size = 0; size <= (size_t)expLen + 2; size++) { \
        char got[300]; \
        memset(got, CANARY, sizeof(got)); \
        int n = lsnprintf(got, size, __VA_ARGS__); \
        checks++; \
        if (n != expLen) { printf("FAIL len  %-14s size=%zu got=%d want=%d\n", #__VA_ARGS__, size, n, expLen); failures++; continue; } \
        for (size_t i = size; i < sizeof(got); i++) \
            if ((unsigned char)got[i] != CANARY) { printf("FAIL overflow %s size=%zu at %zu\n", #__VA_ARGS__, size, i); failures++; break; } \
        if (size > 0) { \
            size_t keep = (size_t)expLen < size - 1 ? (size_t)expLen : size - 1; \
            if (memcmp(got, expect, keep) != 0 || got[keep] != 0) { printf("FAIL text  %s size=%zu got='%s' want='%.*s'\n", #__VA_ARGS__, size, got, (int)keep, expect); failures++; } \
        } \
    } \
    char full[300]; \
    int n2 = lsprintf(full, __VA_ARGS__); \
    checks++; \
    if (n2 != expLen || strcmp(full, expect) != 0) { printf("FAIL sprintf %s got='%s'\n", #__VA_ARGS__, full); failures++; } \
} while (0)

int main(void)
{
    CHECK("hello");
    CHECK("");
    CHECK("%d", 0);
    CHECK("%d", -12345);
    CHECK("%u", 4000000000u);
    CHECK("%x %X", 0xbeefu, 0xbeefu);
    CHECK("%08x", 0x1234u);
    CHECK("%5d|%-5d|%05d", 42, 42, 42);
    CHECK("%+d % d", 7, 7);
    CHECK("%lld", -9000000000000LL);
    CHECK("%llx", 0x123456789abcULL);
    CHECK("%hhu.%hhu.%hhu.%hhu", 192, 168, 1, 254);
    CHECK("%hd", -2);
    CHECK("%s", "LuxiOS");
    CHECK("[%10s]", "cub");
    CHECK("[%-10s]", "cub");
    CHECK("%.3s", "lightning");
    CHECK("%c%c%c", 'L', 'u', 'x');
    CHECK("100%%");
    CHECK("%.*s and %*d", 4, "abcdefg", 6, 99);
    CHECK("; generated by %s%s\nkey = %d\n", "LuxiOS v13.4", "-144f5530", 1);

    printf("%d checks, %d failures\n", checks, failures);
    return failures != 0;
}
