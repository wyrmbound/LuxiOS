"""Turns a rendered mascot PNG into an RGB565 C array for Rosalina.

Usage: make_sprite.py <mascot.png> <size> <out.h>
Transparent areas are composited onto black (the menu background).
"""
import sys
from PIL import Image

src, size, dst = sys.argv[1], int(sys.argv[2]), sys.argv[3]
img = Image.open(src).convert('RGBA').resize((size, size), Image.LANCZOS)
bg = Image.new('RGBA', img.size, (0, 0, 0, 255))
img = Image.alpha_composite(bg, img).convert('RGB')

vals = []
for y in range(size):
    for x in range(size):
        r, g, b = img.getpixel((x, y))
        vals.append((r >> 3) << 11 | (g >> 2) << 5 | (b >> 3))

lines = []
for i in range(0, len(vals), 12):
    lines.append('    ' + ', '.join(f'0x{v:04X}' for v in vals[i:i + 12]) + ',')

with open(dst, 'w', encoding='utf-8', newline='\n') as f:
    f.write(f'''// Generated by tools/make_sprite.py from branding/luxi-mascot.svg -- do not edit by hand.
// Luxi, the LuxiOS mascot: {size}x{size} RGB565, row-major, composited onto black.
#pragma once

#include <3ds/types.h>

#define LUXI_SPRITE_SIZE {size}

static const u16 luxiSprite[LUXI_SPRITE_SIZE * LUXI_SPRITE_SIZE] = {{
''' + '\n'.join(lines) + '\n};\n')
print('ok', dst, len(vals))
